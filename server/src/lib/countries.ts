// The countries a trip can be going to.
//
// One list, server-side, served to the client by `GET /api/countries` — the
// trip sheet's picker is filled from it rather than from a second copy that
// would drift from the one validating what gets saved. Same reasoning as
// lib/currencies.ts, and the same shape.
//
// The country used to be free text, so "Japan", "japan ", "Jappan" and "Tokyo"
// all saved equally well while three features read that one box (the Essentials
// gating, the currency guess, and the analytics grouping). A code is what makes
// those three stop depending on spelling.
//
// 243 entries: ISO 3166-1 alpha-2, officially assigned, minus the five with no
// resident population (AQ, BV, HM, TF, UM). Ordered by name, which is the order
// the picker shows them in; nothing depends on it beyond that.
//
// There is no flag field. A flag is the two regional-indicator code points of
// the alpha-2 code (src/lib/country-flag.ts) — derivable, so storing or serving
// it would make one fact into two.

export interface Country {
  code: string
  name: string
  /**
   * Other spellings this country answers to. Searched, never shown: the picker
   * filters on them so "UK" finds the United Kingdom, and `findCountryByName`
   * resolves them so every key of CURRENCY_BY_COUNTRY — 76 of them, several
   * aliases from the free-text days ('czech republic', 'uae', 'england') —
   * still names a country here. `server/tests/countries.test.ts` asserts that,
   * so a currency guess cannot go missing when this list changes.
   */
  aliases?: string[]
}

