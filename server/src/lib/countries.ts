const BY_CODE = new Map(COUNTRIES.map((c) => [c.code, c]))

const BY_NAME = new Map<string, Country>()
for (const country of COUNTRIES) {
  BY_NAME.set(country.name.toLowerCase(), country)
  for (const alias of country.aliases ?? []) BY_NAME.set(alias.toLowerCase(), country)
}

/** Uppercase code → entry. What validation and every read go through. */
export const COUNTRY_BY_CODE: Record<string, Country> = Object.fromEntries(BY_CODE)

/** A code in any case to its country, or undefined. Never guesses. */
export function findCountryByCode(code: string | null | undefined): Country | undefined {
  if (!code) return undefined
  return BY_CODE.get(code.trim().toUpperCase())
}

/**
 * A complete name to its country, or undefined.
 *
 * Trimmed and case-insensitive, matching the name or any alias — and exact
 * otherwise. Deliberately not fuzzy: guessing that "Jappan" means Japan is how
 * the wrong country gets stored with confidence, so a near-miss is a refusal
 * (services/trips.ts) rather than a correction.
 */
export function findCountryByName(name: string | null | undefined): Country | undefined {
  if (!name) return undefined
  return BY_NAME.get(name.trim().toLowerCase())
}
