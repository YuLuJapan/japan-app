// One-off asset pipeline for the homepage sushi sequence.
//
// Reads a directory of extracted video frames, re-encodes them into
// `public/sushi/` as a clean frame-001.jpg… run, and writes
// `src/generated/sushi-frames.ts` describing what it produced.
//
//   node scripts/build-sushi-frames.mjs <source-dir> [width] [quality]
//
// Frames are kept at the source's native width by default. The hero crops to
// roughly the middle 40% of each frame, so downscaling here just means
// upscaling that crop back on screen.
//
// Any input naming works: the directory is listed and sorted by the first
// number in each filename. Frames left over from a longer previous clip are
// deleted, so swapping in shorter footage can't strand orphans.
//
// The generated module carries a content hash. The component appends it to
// every frame URL, which is what stops a service worker's CacheFirst rule from
// serving half a stale generation alongside half a fresh one — the failure
// that shipped once already. Frame count lives there too, so it can't drift
// from the files on disk.
//
// Re-run it if the source clip is ever replaced; the output is committed, so
// this is not part of the normal build.
import sharp from 'sharp'
import { createHash } from 'node:crypto'
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const SRC = process.argv[2]
const WIDTH = Number(process.argv[3] || 1280)
const QUALITY = Number(process.argv[4] || 68)

if (!SRC) {
  console.error('usage: node scripts/build-sushi-frames.mjs <source-dir> [width] [quality]')
  process.exit(1)
}

const OUT = resolve(HERE, '..', 'public', 'sushi')
const GENERATED = resolve(HERE, '..', 'src', 'generated', 'sushi-frames.ts')
mkdirSync(OUT, { recursive: true })
mkdirSync(dirname(GENERATED), { recursive: true })

// Sort by the first number in the name, so frame 2 doesn't land after frame 10
// when a source drops the zero padding.
const leadingNumber = (name) => {
  const m = name.match(/\d+/)
  return m ? Number(m[0]) : Number.POSITIVE_INFINITY
}

const sources = readdirSync(SRC)
  .filter((f) => /\.(jpe?g|png)$/i.test(f))
  .sort((a, b) => leadingNumber(a) - leadingNumber(b) || a.localeCompare(b))

if (!sources.length) {
  console.error(`no images found in ${SRC}`)
  process.exit(1)
}

const pad = (n) => String(n).padStart(3, '0')

const hash = createHash('sha256')
let total = 0
let height = 0

for (let i = 0; i < sources.length; i++) {
  const { data, info } = await sharp(resolve(SRC, sources[i]))
    .resize({ width: WIDTH })
    .jpeg({ quality: QUALITY, progressive: true, mozjpeg: true })
    .toBuffer({ resolveWithObject: true })

  writeFileSync(resolve(OUT, `frame-${pad(i + 1)}.jpg`), data)
  hash.update(data)
  total += data.length
  height = info.height
}

// Drop anything left over from a previous, longer clip.
let removed = 0
for (const f of readdirSync(OUT)) {
  const n = leadingNumber(f)
  if (!Number.isFinite(n) || n > sources.length) {
    rmSync(resolve(OUT, f))
    removed += 1
  }
}

const version = hash.digest('hex').slice(0, 8)

writeFileSync(
  GENERATED,
  `// Generated by scripts/build-sushi-frames.mjs — do not edit by hand.
//
// ASSET_VERSION is a content hash of every frame. It is appended to each frame
// URL so a regenerated sequence gets fresh URLs; without it the service
// worker's CacheFirst rule happily mixes an old cached generation with a new
// one, and the animation jumps mid-scroll.
export const FRAME_COUNT = ${sources.length}
export const FRAME_WIDTH = ${WIDTH}
export const FRAME_HEIGHT = ${height}
export const ASSET_VERSION = '${version}'
`
)

console.log(
  `${WIDTH}x${height} q${QUALITY}: ${sources.length} frames, ` +
    `${(total / 1048576).toFixed(2)} MB, ${Math.round(total / sources.length / 1024)} KB avg`
)
if (removed) console.log(`removed ${removed} stale frame(s)`)
console.log(`asset version: ${version}`)
console.log(`wrote ${GENERATED}`)
